import json
from dataclasses import dataclass, field, asdict
from typing import List, Dict, Optional, Any
from pathlib import Path

from arb.models.presentation import ResumeDocument, RenderedBullet
from arb.models.domain import CanonicalProfile, Fact


@dataclass
class BulletAudit:
    entity_type: str                       # "project" | "experience"
    entity_name: str                       # e.g. "TransitOS"
    bullet_text: str
    is_grounded: bool
    source_fact_ids: List[str]
    supporting_facts: List[Dict[str, Any]] = field(default_factory=list)
    warning: Optional[str] = None


@dataclass
class AuditReport:
    total_bullets: int
    grounded_bullets: int
    ungrounded_bullets: int
    groundedness_score: float              # Percentage 0.0 - 100.0
    items: List[BulletAudit] = field(default_factory=list)
    model_used: str = ""

    def to_dict(self) -> dict:
        return asdict(self)

    def to_markdown(self) -> str:
        lines = [
            "# 🛡️ ARB Proof Mode: Evidence Grounding Audit",
            "",
            f"**Model Engine:** `{self.model_used}`  ",
            f"**Groundedness Score:** `{self.groundedness_score:.1f}%` ({self.grounded_bullets}/{self.total_bullets} verified)  ",
            f"**Status:** {'✅ PASSED — All claims strictly grounded in source evidence' if self.ungrounded_bullets == 0 else '⚠️ WARNING — Unsupported claims detected'}",
            "",
            "---",
            "",
            "## Claim-to-Evidence Traceability Matrix",
            ""
        ]

        # Group by entity
        current_entity = None
        for item in self.items:
            header = f"### {item.entity_type.capitalize()}: {item.entity_name}"
            if header != current_entity:
                current_entity = header
                lines.append(header)
                lines.append("")

            status_icon = "✅" if item.is_grounded else "❌"
            lines.append(f"- {status_icon} **\"{item.bullet_text}\"**")

            if item.is_grounded:
                for f in item.supporting_facts:
                    metric_str = f" [Metric: `{f['metric']}`]" if f.get("metric") else ""
                    sources_str = ", ".join([f"{s.get('type')}:{s.get('id')}" for s in f.get("source_refs", [])])
                    lines.append(f"  - ↳ Grounded in Fact `{f['id']}`{metric_str}")
                    lines.append(f"    - Provenance: `{sources_str or 'verified canonical'}`")
                    lines.append(f"    - Raw Evidence: *\"{f['text']}\"*")
            else:
                lines.append(f"  - ⚠️ **UNGROUNDED CLAIM**: {item.warning or 'No verified source facts support this claim.'}")

            lines.append("")

        lines.append("---")
        lines.append("*Generated automatically by Auto Resume Builder (ARB) Proof Mode.*")
        return "\n".join(lines)


class EvidenceAuditor:
    """
    Validates that every bullet point generated by Gemma or the LLM
    strictly references valid, atomic Fact domain objects and is grounded in
    verifiable source provenance (commits, READMEs, documents).
    """

    def audit(self, document: ResumeDocument, profile: CanonicalProfile, model_name: str = "") -> AuditReport:
        # 1. Build comprehensive fact lookup from profile
        fact_map: Dict[str, Fact] = {}

        for proj in profile.projects:
            for f in proj.facts:
                fact_map[f.id] = f

        for exp in profile.experience:
            for f in exp.facts:
                fact_map[f.id] = f

        audited_items: List[BulletAudit] = []

        # 2. Audit Project bullets
        for proj in document.projects:
            for bullet in proj.bullets:
                audit_item = self._audit_single_bullet(
                    bullet=bullet,
                    entity_type="project",
                    entity_name=proj.name,
                    fact_map=fact_map
                )
                audited_items.append(audit_item)

        # 3. Audit Experience bullets
        for exp in document.experience:
            for bullet in exp.bullets:
                audit_item = self._audit_single_bullet(
                    bullet=bullet,
                    entity_type="experience",
                    entity_name=exp.organization,
                    fact_map=fact_map
                )
                audited_items.append(audit_item)

        total = len(audited_items)
        grounded = sum(1 for item in audited_items if item.is_grounded)
        ungrounded = total - grounded
        score = (grounded / total * 100.0) if total > 0 else 100.0

        return AuditReport(
            total_bullets=total,
            grounded_bullets=grounded,
            ungrounded_bullets=ungrounded,
            groundedness_score=score,
            items=audited_items,
            model_used=model_name or "Gemma 4"
        )

    def _audit_single_bullet(
        self,
        bullet: RenderedBullet,
        entity_type: str,
        entity_name: str,
        fact_map: Dict[str, Fact]
    ) -> BulletAudit:
        if not bullet.source_fact_ids:
            return BulletAudit(
                entity_type=entity_type,
                entity_name=entity_name,
                bullet_text=bullet.text,
                is_grounded=False,
                source_fact_ids=[],
                supporting_facts=[],
                warning="Hallucination risk: Model generated bullet without citing any source fact IDs."
            )

        supporting_facts: List[Dict[str, Any]] = []
        missing_ids: List[str] = []

        for fid in bullet.source_fact_ids:
            if fid in fact_map:
                f = fact_map[fid]
                supporting_facts.append({
                    "id": f.id,
                    "text": f.text,
                    "fact_type": f.fact_type,
                    "metric": f.metric,
                    "source_refs": [s.to_dict() if hasattr(s, "to_dict") else dict(s) for s in f.source_refs]
                })
            else:
                missing_ids.append(fid)

        if missing_ids:
            return BulletAudit(
                entity_type=entity_type,
                entity_name=entity_name,
                bullet_text=bullet.text,
                is_grounded=False,
                source_fact_ids=bullet.source_fact_ids,
                supporting_facts=supporting_facts,
                warning=f"Invalid fact citation: cited IDs {missing_ids} do not exist in canonical profile."
            )

        return BulletAudit(
            entity_type=entity_type,
            entity_name=entity_name,
            bullet_text=bullet.text,
            is_grounded=True,
            source_fact_ids=bullet.source_fact_ids,
            supporting_facts=supporting_facts
        )
